#!/usr/bin/env python3
"""Generate the link units: TU sources under src/tu/ and config/RFEE01/units.json.

Input: config/RFEE01/link_select.txt, one unit per line:
    game <start>-<end>          game code range (a TU or link unit of docs/tu_map.tsv)
    lib  <lib source key>       a source of lib/map.json (e.g. ogws/src/MSL/k_rem_pio2.c)
For each unit the source is generated (game: gen_tu.py from the per-function files) or taken
from lib/ (library), compiled with its flags and placed with place.py. A unit becomes
"Matching" only if place.py accepts it (every byte and relocation of every section it emits
equals main.dol, and no symbol the rest of the link needs disappears); otherwise it is left
out (its range stays dtk asm) and the reason is printed.

Then run tools/build/gen_config.py (splits.txt, symbols.txt renames) and configure.py.
Usage: python3 -I tools/build/gen_units.py [--select FILE] [--dry-run]
"""
