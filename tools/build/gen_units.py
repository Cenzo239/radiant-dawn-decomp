def flat_flags(flags):
    out = []
    for f in flags:
        out += shlex.split(f)
    return out


ALIASES = os.path.join(ROOT, "src/tu/lib_aliases.h")


def write_aliases(renames):
    """Game sources call library functions by their fn_ names; once a library object is linked
    under its real names, the game TUs see them through these defines."""
    lines = ["/* Generated by tools/build/gen_units.py: fn_/lbl_ names of linked library symbols. */\n",
             "#ifndef TU_LIB_ALIASES_H\n#define TU_LIB_ALIASES_H\n"]
    for old, new in sorted(renames.items()):
        if re.fullmatch(r"[A-Za-z_]\w*", new):
            lines.append(f"#define {old} {new}\n")
    lines.append("#endif\n")
    text = "".join(lines)
    os.makedirs(os.path.dirname(ALIASES), exist_ok=True)
    if not os.path.exists(ALIASES) or open(ALIASES).read() != text:
        open(ALIASES, "w").write(text)


def game_unit(a, b, ok_files, renames, asm=(), asm_data=False, c_native=False, hdr_fix=None, prune=False, lead=(),
              def_data=(), lit_rw=(), lit_order=False, cpp_redir=(), pp_hoist=False, inline_copies=False):
    fns = G.functions_in(a, b)
    note = f"game code 0x{a:08X}..0x{b:08X} ({len(fns)} functions)"
    if asm:
        # the functions listed after asm= (link_select.txt) are emitted from their original
        # instructions; every other function must have an exact definition
        bad = [f for f in fns if f not in ok_files and f not in asm]
        text, lang, problems, asm_fns, data_names = G.generate(fns, ok_files, note, fallback=True,
                                                               force_asm=set(asm), asm_data=asm_data,
                                                               c_native=c_native, hdr_fix=hdr_fix,
                                                               prune_data=prune, lead_data=lead, def_data=def_data,
                                                               lit_rw=lit_rw, lit_order=lit_order, cpp_redir=cpp_redir, pp_hoist=pp_hoist, inline_copies=inline_copies)
        problems += [f"{f}: no exact definition and not listed as asm" for f in bad]
    else:
        text, lang, problems, asm_fns, _d = G.generate(fns, ok_files, note, fallback=True, c_native=c_native,
                                                       hdr_fix=hdr_fix, prune_data=prune, lead_data=lead, def_data=def_data,
                                                       lit_rw=lit_rw, lit_order=lit_order, cpp_redir=cpp_redir, pp_hoist=pp_hoist, inline_copies=inline_copies)
        problems += [f"{f}: no exact definition" for f in asm_fns]
    region = TA.region_of(a)
    rel = f"tu/game/{region}/tu_{a:08X}{lang}"
    srcs = sorted({ok_files[f][0] for f in fns if f in ok_files and f not in asm_fns})
    smaps = G.symbol_map_renames(srcs)
    lib_named = {o for o in smaps if o in LIB_RENAMES}
    bad = [o for o in lib_named if LIB_RENAMES[o] != smaps[o]]
    if bad:
        problems = problems + [f"symbol map renames {bad[0]}, which a library source names {LIB_RENAMES[bad[0]]}"]
    path = os.path.join(ROOT, "src", rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    unit = {"name": rel, "kind": "game", "cc": "GC/3.0a5.2", "functions": len(fns),
            "sources": sorted({ok_files[f][0] for f in fns if f in ok_files and f not in asm_fns})}
    if asm_fns:
        S = G._dol()[1]
        unit["asm_functions"] = asm_fns
        unit["asm_bytes"] = sum(S[f].size for f in asm_fns)
        unit["asm_data"] = data_names
    if problems:
        return unit, problems
    if smaps:
        unit["renames"] = {o: n for o, n in smaps.items() if o not in lib_named}
    body = text

    def write(undefs):
        t = body
        if renames:
            t = '#include "tu/lib_aliases.h"\n' + "".join(f"#undef {o}\n" for o in sorted(undefs) if o not in lib_named) + t
        # MWLD dead-strips functions nothing references (dtk's asm keeps them); keep every function
        t = "#pragma force_active on\n" + t
        old = open(path).read() if os.path.exists(path) else None
        if old != t:
            open(path, "w").write(t)
    undefs = set(smaps)
    write(undefs)
    obj = PL.compile_src(os.path.join("src", rel))
    if smaps:
        _ren, defd = PL.settle_renames(obj, smaps)
        if {o for o in undefs if o not in lib_named} != {o for o in defd if o not in lib_named}:
            # only the unit that defines a label #undefs its alias (see try_units.run_once)
            os.unlink(obj)
            write(defd)
            obj = PL.compile_src(os.path.join("src", rel))
    if smaps:
        # (a class of a file namespace: its vtable has the namespaced name in the object)
        smaps = PL.object_renames(obj, smaps)
        if unit.get("renames"):
            unit["renames"] = {o: n for o, n in smaps.items() if o not in lib_named}
    try:
        P, dropped = PL.place_game(obj, {**{new: old for old, new in renames.items()},
                                         **{n: o for o, n in smaps.items()}})
        if dropped:
            unit["dead_stripped"] = dropped
    finally:
        os.unlink(obj)
    unit["ranges"] = {k: ["0x%08X" % x, "0x%08X" % y] for k, (x, y) in P.ranges.items()}
    if P.size_fixes:
        unit["symbol_sizes"] = {k: "0x%X" % v for k, v in P.size_fixes.items()}
    if P.ranges.get(".text") != (a, b):
        P.errors.insert(0, f".text placed at {P.ranges.get('.text')}, not the requested range")
    return unit, P.errors


GLOBAL_RENAMES = {}
LIB_RENAMES = {}
_EXT_FUNCS = None


def lib_unit(key, lib_map, manifest):
    S, _dol, by_addr = PL.dolmodel()
    m = manifest[key]
    src = os.path.join("lib", key)
    extra = []
    obj = PL.compile_src(src, m["cc"], flat_flags(m["flags"]))
    # object name -> symbols.txt name, by address (lib/map.json functions and symbols)
    addr_name = {}
    for s in sorted(S.values(), key=lambda s: s.type != "function"):   # a function wins over a label
        addr_name.setdefault((s.sec, s.addr), s.name)
    names = {}
    for fn, (addr, size, st) in lib_map["sources"][key]["functions"].items():
        if "@unnamed@" in fn and "NonCopyable" in fn:
            continue   # a TU-local dtor the original link dead-stripped; remap.py matched it to another TU's copy
        n = addr_name.get((".text", addr))
        if n:
            names[fn] = n
    secs, syms, _r = PL.parse_elf(obj)
    # functions this object only references (defined by another library source): their base names
    # from lib/map.json (the DOL address of the function that source maps under that name)
    global _EXT_FUNCS
    if _EXT_FUNCS is None or _EXT_FUNCS[0] is not lib_map:
        ef = {}
        for k2, ent in lib_map["sources"].items():
            for fn2, (a2, _z2, _s2) in ent["functions"].items():
                ef.setdefault(fn2, set()).add(a2)
        _EXT_FUNCS = (lib_map, {f: next(iter(a)) for f, a in ef.items() if len(a) == 1})
    for s_ in syms:
        if s_["shndx"] == 0 and s_["name"] and s_["name"] not in names and s_["name"] in _EXT_FUNCS[1]:
            n_ = addr_name.get((".text", _EXT_FUNCS[1][s_["name"]]))
            if n_:
                names[s_["name"]] = n_
    S_all = S
    for s in syms:
        if s["name"] in lib_map["symbols"] and s["name"] not in names:
            a = lib_map["symbols"][s["name"]]
            sec = M.section_of(a)
            n = addr_name.get((sec, a))
            if n:
                names[s["name"]] = n
    inv = {new: old for old, new in GLOBAL_RENAMES.items()}
    inv.update(names)
    dropped = []
    drops = []
    wd = set()
    keep_data = []
    natural = False
    try:
        P = PL.place(obj, inv)
        if any((e.startswith("function ") and "not in symbols.txt" in e) or "breaks contiguity" in e
               or "cannot derive a single base" in e
               or (e.startswith("function ") and " size 0x" in e)
               or "no references from code" in e
               # weak data (RTTI/vtable) whose DOL copy lies in another object: the strip retry cuts it out
               or (P.weak_else and (e.startswith(".data") or e.startswith(".rodata")))
               # a constant pool with an entry only dead code used (the DOL link stripped it)
               or (e.startswith((".sdata2:", ".rodata:", ".sdata:")) and "words differ from the DOL" in e)
               for e in P.errors):
            # (not on size/contiguity errors: a weak copy that the model drops because its DOL
            # twin lies elsewhere may be the copy MWLD links, the first in link order;
            # snd_DisposeCallbackManager.cpp's __dt__Q34nw4r2ut12LinkListNodeFv shifted 0x40)
            # functions the original link dead-stripped: model MWLD's dead-stripping (keep what
            # main.dol has and what that references) and place the rest; the link itself
            # strips the same functions (nothing references them)
            def in_dol(n):
                t = inv.get(n, n)
                return S[t].addr if t in S and (not t.startswith("@") or PL._THUNK.match(t)) and (n in inv or not n.startswith("@") or PL._THUNK.match(n)) else None
            # MWLD keeps the unreferenced data of some objects: try the model without data
            # stripping, then with .bss/.sbss kept, then with all data kept
            for nat, kd in ((False, ()), (False, (".bss", ".sbss")),
                            (False, (".bss", ".sbss", ".rodata", ".sdata", ".sdata2")),
                            (False, (".bss", ".sbss", ".data", ".sdata", ".rodata", ".sdata2")),
                            (False, (".bss", ".sbss", ".data", ".sdata")),
                            (True, ()), (True, (".bss", ".sbss"))):
                parsed, dropped = PL.strip_object(obj, in_dol, kd, nat)
                inv2 = dict(inv, **parsed[5])     # functions found in the DOL by position and bytes
                P2 = PL.place(parsed, inv2)
                # weak data (vtable/RTTI copies) whose DOL copy lies in another object: strip them
                # too (and cut them out of the object with dropfn below)
                wd = set()
                for _i in range(4):
                    if not (P2.weak_else - wd):
                        break
                    wd |= P2.weak_else
                    parsed, dropped = PL.strip_object(obj, in_dol, kd, nat, wd)
                    inv2 = dict(inv, **parsed[5])
                    P2 = PL.place(parsed, inv2)
                if not P2.errors:
                    keep_data = list(kd)
                    natural = nat
                    break
            drops = []
            if not P2.errors:
                # weak copies whose single DOL copy lies in another object: MWLD would keep this
                # object's copy (first definition), so the build cuts them out of the compiled
                # object (tools/build/dropfn.py, units.json "drop_functions") and the calls bind
                # to the other copy
                drops = sorted(n for n in (PL.LAST_ELSE | PL.LAST_FORCE | wd) if n in set(dropped))
                if drops:
                    tmp = obj + ".drop.o"
                    r = subprocess.run([sys.executable, "-I", os.path.join(HERE, "dropfn.py"), obj, tmp, *drops],
                                       capture_output=True, text=True)
                    if r.returncode:
                        P2.errors.append("dropfn: " + (r.stderr.strip().splitlines() or ["failed"])[-1])
                    else:
                        try:
                            parsed3, _d3 = PL.strip_object(tmp, in_dol, kd, natural, wd)
                            P3 = PL.place(parsed3, dict(inv, **parsed3[5]))
                        finally:
                            os.unlink(tmp)
                        if P3.errors:
                            P2.errors += ["(after dropfn) " + e for e in P3.errors[:3]]
            if not P2.errors:
                inv = inv2
                names.update(parsed[5])
            if not P2.errors:
                P = P2
                secs, syms, _r = parsed[:3]
            else:
                dropped = []
                P.errors = P2.errors + ["(dead-stripped model) " + e for e in P.errors[:2]]
    finally:
        os.unlink(obj)
    # retries with flags the manifest does not record:
    #  - force_active: functions the original link kept although nothing references them
    #    (dtk's asm keeps them too); only the .comment flags change
    #  - C++ exceptions on: the original object had exception tables (extab/extabindex)
    fixable = ("MWLD would dead-strip", "(exception table)")
    if P.errors and all(any(k in e for k in fixable) for e in P.errors) and not dropped:
        exc = any("(exception table)" in e for e in P.errors)
        tries = ([['-Cpp_exceptions on'], ['-Cpp_exceptions on', '-pragma "force_active on"']] if exc
                 else [['-pragma "force_active on"']])
        for t in tries:
            obj = PL.compile_src(src, m["cc"], flat_flags(m["flags"] + t))
            try:
                P2 = PL.place(obj, inv)
            finally:
                os.unlink(obj)
            if not P2.errors:
                P, extra = P2, t
                break
    # every symbol the object references but does not define must exist under that name in the
    # final symbols.txt (a name the rename pass skipped, e.g. two names at one address, would be
    # undefined at link time)
    defined = {s["name"] for s in syms if s["shndx"]}
    refd = {t for rl in _r.values() for _o, _t, t, _a, _s in rl}
    ext_rn = {}
    for t in sorted(refd - defined):
        if not t or t.startswith("@"):
            continue
        base = inv.get(t, t)
        final = GLOBAL_RENAMES.get(base, base)
        if base in S_all and final != t:
            # a label symbols.txt has at the same address under the referenced name is fine
            if t in S_all and S_all[t].addr == S_all[base].addr and S_all[t].sec == S_all[base].sec:
                continue
            # an unnamed DOL function/label the object names: the unit renames it
            if re.match(r"(fn|lbl)_[0-9A-Fa-f]+$", final):
                ext_rn[base] = t
                continue
            P.errors.append(f"references {t}, which the link knows as {final}")
    # rename symbols.txt entries to the object's names (only global object symbols that differ)
    # (static symbols keep their symbols.txt name: the link does not need it, and statics of
    # one name in several objects (Callback, OnShutdown) would clash)
    glob = {s["name"] for s in syms if s["shndx"] and s["shndx"] < 0xFF00 and s.get("bind", 1) != 0}
    renames = {}
    for new, old in names.items():   # functions first: a label at a function's address
        if new != old and new in glob and old not in renames:   # (__RAS_..._begin) keeps the function name
            renames[old] = new
    for b_, t_ in sorted(ext_rn.items()):
        renames.setdefault(b_, t_)
    for un, nm in sorted(P.adopt.items()):
        if un not in renames and un not in GLOBAL_RENAMES:
            renames[un] = nm
    for tname, un in sorted(P.ext_resolved.items()):
        # a referenced symbol that the DOL only has as an unnamed label: name it as the object does
        if un not in renames and un not in GLOBAL_RENAMES:
            renames[un] = tname
    if dropped:
        # a dead-stripped object must not take over symbols that another library source names
        # (identical small functions, e.g. AI and VI callback setters, map to either)
        clash = [f"{o} ({GLOBAL_RENAMES[o]})" for o, n in renames.items() if o in GLOBAL_RENAMES and GLOBAL_RENAMES[o] != n
                 and not (o in S_all and S_all[o].size <= 8)]   # (leaf stubs are identical in every source)
        if clash:
            P.errors.append(f"dead-stripped object would rename library symbol {clash[0]}")
    name = "lib/" + key
    S_ = PL.dolmodel()[0]
    defs = sorted({inv.get(s["name"], s["name"]) for s in syms if s["shndx"] and s["shndx"] < 0xFF00 and s["type"] in (1, 2)
                   and inv.get(s["name"], s["name"]) in S_})
    unit = {"name": name, "kind": "lib", "lib_source": key, "group": key.split("/")[0], "_defs": defs,
            "functions": len(P.functions), "renames": renames,
            **({"extra_cflags": extra} if extra else {}),
            **({"dead_stripped": dropped} if dropped else {}),
            **({"drop_functions": drops} if dropped and drops else {}),
            **({"keep_data": keep_data} if dropped and keep_data else {}),
            **({"_static_out": P.static_outside} if P.static_outside else {}),
            **({"symbol_sizes": {k: "0x%X" % v for k, v in P.size_fixes.items()}} if P.size_fixes else {}),
            "ranges": {k: ["0x%08X" % x, "0x%08X" % y] for k, (x, y) in P.ranges.items()}}
    return unit, P.errors


def drop_static_refs(units, failed):
    """A library object that keeps a symbol static which code outside it references: fine when
    that code is compiled C too (it has its own reference), an undefined symbol at link time
    when the code stays asm (dtk's objects reference it by its symbols.txt name)."""
    S = PL.dolmodel()[0]
    spans = sorted((int(u["ranges"][".text"][0], 16), int(u["ranges"][".text"][1], 16), u)
                   for u in units if ".text" in u.get("ranges", {}))
    starts = [a for a, _b, _u in spans]
    import bisect

    def compiled(f):
        o = S.get(f)
        if o is None or o.type != "function":
            return True     # data words that look like addresses: no symbol reference
        k = bisect.bisect_right(starts, o.addr) - 1
        if k < 0 or not spans[k][0] <= o.addr < spans[k][1]:
            return False
        return f not in spans[k][2].get("asm_functions", ())
    gone = set()
    for u in list(units):
        bad = [(n, r) for n, rs in u.pop("_static_out", {}).items() for r in rs if not compiled(r)]
        if bad:
            units.remove(u)
            gone |= set(u.get("renames", {}))
            failed.append((u["name"], [f"{bad[0][0]} is static in the object but {bad[0][1]} (asm) references it"]))
            print(f"SKIP {u['name']}: {bad[0][0]} is static in the object but {bad[0][1]} (asm) references it")
    return gone


def drop_small_gaps(units, failed, GC):
    """dtk cannot auto-split a data gap of less than 8 bytes that starts at 4 mod 8 between two
    splits ("Unsplit data ... to next split"): drop the game unit that ends at such a gap (or
    starts after it), until none is left."""
    while True:
        spans = {}
        for x, y, n in GC.base_ranges():
            spans.setdefault(M.section_of(x), []).append((x, y, None))
        for u in units:
            for sec, (x, y) in u["ranges"].items():
                spans.setdefault(sec, []).append((int(x, 16), int(y, 16), u))
        bad = None
        for sec, lst in spans.items():
            if sec in (".text", ".init", ".ctors", ".dtors", "extab", "extabindex"):
                continue
            lst.sort(key=lambda t: t[0])
            for (a, b, u1), (c, d, u2) in zip(lst, lst[1:]):
                if 0 < c - b < 8 and b % 8:
                    bad = next((u for u in (u1, u2) if u is not None and u["kind"] == "game"), None)
                    if bad:
                        print(f"SKIP {bad['name']}: leaves a {c - b}-byte {sec} gap at 0x{b:08X} that dtk cannot split")
                        break
            if bad:
                break
        if not bad:
            return
        units.remove(bad)
        failed.append((bad["name"], ["small data gap"]))


def keep_alive(units):
    """A function or object of a library object that only asm-fallback functions reference
    (opwords carry no relocation) would be dead-stripped by MWLD: compile that library object
    with force_active on (only the .comment flags change)."""
    S = PL.dolmodel()[0]
    asm = {f for u in units for f in u.get("asm_functions", []) + u.get("asm_data", [])}
    if not asm:
        return
    for u in units:
        if u["kind"] != "lib" or u.get("extra_cflags") or u.get("dead_stripped"):
            continue
        defs = set(u.get("_defs", []))
        hit = [d for d in defs if S[d].refby & asm and not (S[d].refby - asm - defs)]
        if hit:
            u["extra_cflags"] = ['-pragma "force_active on"']
            print(f"NOTE {u['name']}: force_active ({', '.join(hit[:3])} referenced only from asm functions)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--select", default=os.path.join(CFG, "link_select.txt"))
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("-j", type=int, default=8)
    a = ap.parse_args()
    ok_files = G.load_ok_files()
    lib_map = json.load(open(os.path.join(ROOT, "lib/map.json")))
    manifest = json.load(open(os.path.join(ROOT, "lib/manifest.json")))
    units, failed = [], []
    entries = []
    for line in open(a.select):
        line = line.split("#", 1)[0].strip()
        if line:
            entries.append(line)
    sys.path.insert(0, HERE)
    import gen_config as GC
    renames = GC.lib_renames()
    GLOBAL_RENAMES.update(renames)
    # library units first: their renames are needed by the game units
    def run(line):
        kind, arg = line.split(None, 1)
        if kind == "game":
            rng, *opts = arg.split()
            x, y = (int(v, 16) for v in rng.split("-"))
            asm = next((o[4:].split(",") for o in opts if o.startswith("asm=")), ())
            hf = next((G.parse_hdr_fix(o[5:]) for o in opts if o.startswith("hfix=")), None)
            ld = next((o[5:].split(",") for o in opts if o.startswith("lead=")), ())
            dd = next((o[4:].split(",") for o in opts if o.startswith("def=")), ())
            rw = next((o[3:].split(",") for o in opts if o.startswith("rw=")), ())
            try:
                return line, game_unit(x, y, ok_files, renames, asm, "lit" if "asmlit" in opts else "asmdata" in opts,
                                       "cnative" in opts, hf, "prune" in opts, ld, dd, rw, "order" in opts,
                                       next((o[7:].split(",") for o in opts if o.startswith("credir=")), ()),
                                       "hoist" in opts,
                                       next((o[4:].split(",") if o[4:] else [] for o in opts if o == "inl" or o.startswith("inl=")), False))
            except (OSError, ValueError, KeyError) as e:   # e.g. a source moved since survey.py ran
                return line, ({}, [f"generator: {type(e).__name__}: {e}"[:300]])
        if kind == "lib":
            return line, lib_unit(arg, lib_map, manifest)
        sys.exit(f"bad line: {line}")

    def collect(line, unit, errors):
        if errors:
            failed.append((line, errors))
            print(f"SKIP {line}: {errors[0]}" + (f" (+{len(errors) - 1} more)" if len(errors) > 1 else ""))
            return
        rng = [(int(x, 16), int(y, 16)) for x, y in unit["ranges"].values()]
        clash = next((n for x, y, n in GC.base_ranges() if any(a < y and x < b for a, b in rng)), None) or \
            next((u["name"] for u in units for x, y in (map(lambda v: int(v, 16), r) for r in u["ranges"].values())
                      if any(a < y and x < b for a, b in rng)), None)
        if clash:
            failed.append((line, [f"overlaps {clash}"]))
            print(f"SKIP {line}: overlaps {clash}")
            return
        taken = {}
        for o, n in renames.items():
            taken.setdefault(n, o)
        dup = next((n for o, n in unit.get("renames", {}).items() if taken.get(n, o) != o), None)
        if dup:
            failed.append((line, [f"renames a symbol to {dup}, which another symbol already has"]))
            print(f"SKIP {line}: renames a symbol to {dup}, which another symbol already has")
            return
        unit["status"] = "Matching"
        units.append(unit)
        renames.update(unit.get("renames", {}))
        GLOBAL_RENAMES.update(unit.get("renames", {}))
        print(f"OK   {line}: {unit['name']} {unit['ranges']}")

    # library units first: their renames are needed by the game units
    PL.dolmodel()
    PL.eh_entries()
    G._dol()
    asm_listed = {f for l in entries if l.startswith("game") for o in l.split() if o.startswith("asm=")
                  for f in o[4:].split(",")}
    S_ = PL.dolmodel()[0]
    for line in [l for l in entries if l.startswith("lib")]:
        line, (unit, errors) = run(line)
        if not errors and unit.get("dead_stripped"):
            # force_active (keep_alive) would also keep the stripped functions: a kept symbol
            # that only asm-fallback functions reference cannot be kept alive
            defs = set(unit.get("_defs", []))
            hit = [d for d in defs if S_[d].refby & asm_listed and not (S_[d].refby - asm_listed - defs)]
            if hit:
                errors = [f"dead-stripped object, but {hit[0]} is referenced only from asm functions"]
        collect(line, unit, errors)
    LIB_RENAMES.update(renames)
    # labels the symbol maps of the selected game units' files rename (vtables, ...): other game
    # units reach them through lib_aliases.h, the unit that defines them #undefs the alias
    for l in entries:
        if not l.startswith("game"):
            continue
        rng, *opts = l.split(None, 1)[1].split()
        x, y = (int(v, 16) for v in rng.split("-"))
        asm = set(next((o[4:].split(",") for o in opts if o.startswith("asm=")), ()))
        fs = sorted({ok_files[f][0] for f in G.functions_in(x, y) if f in ok_files and f not in asm})
        for o, n in G.symbol_map_renames(fs).items():
            if o not in renames:
                renames[o] = n
    write_aliases(renames)
    import concurrent.futures as cf
    import multiprocessing
    # worker processes (fork: they inherit the warmed-up caches); generation and placement
    # are Python, threads were bound by the GIL
    _RUN[:] = [run]
    with cf.ProcessPoolExecutor(a.j, mp_context=multiprocessing.get_context("fork")) as ex:
        for line, (unit, errors) in ex.map(_run_line, [l for l in entries if l.startswith("game")], chunksize=4):
            collect(line, unit, errors)
    write_aliases(renames)
    gone = drop_static_refs(units, failed)
    if gone:
        base = GC.lib_renames()
        for o in gone:
            if o in base:
                renames[o] = base[o]
            else:
                renames.pop(o, None)
        for u in units:
            renames.update(u.get("renames", {}))
        write_aliases(renames)
    drop_small_gaps(units, failed, GC)
    keep_alive(units)
    for u in units:
        u.pop("_defs", None)
    if not a.dry_run:
        json.dump({"generated_by": "tools/build/gen_units.py", "units": units},
                  open(os.path.join(CFG, "units.json"), "w"), indent=1)
        # generated TU sources of units that are no longer selected
        keep = {os.path.normpath(os.path.join(ROOT, "src", u["name"])) for u in units if u["kind"] == "game"}
        for dp, _dn, fns in os.walk(os.path.join(ROOT, "src/tu/game")):
            for fn in fns:
                pth = os.path.normpath(os.path.join(dp, fn))
                if pth not in keep and fn.startswith("tu_") and \
                        "Generated by tools/build/gen_tu.py" in open(pth, errors="replace").read(400):
                    os.unlink(pth)
    print(f"{len(units)} units Matching, {len(failed)} skipped")
    return 0


_RUN = []


def _run_line(line):
    return _RUN[0](line)


if __name__ == "__main__":
    sys.exit(main())
