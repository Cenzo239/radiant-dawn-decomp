#!/usr/bin/env python3
"""Refuse commits and pushes that would put game data into the repository.

The repository is private and must never contain anything from the disc (or derived from
it): disc files, decompressed/extracted assets, generated port data, game text, saves,
screenshots, or the HD texture pack. This script checks every blob that is about to enter
the repository and rejects it when

  1. hash   its content is byte-identical to a file in the local game-data index: every file
            under orig/RFEE01 (the extracted disc), the HD pack / mods folder, saves and playtest
            references (see index_roots). build/ is not indexed: it holds copies of tracked
            source; generated data there is caught by the marker/type/binary rules. Only on a
            machine that has those files; the index lives in <git-common-dir>/fe10-guard/.
  2. path   it lives where game data lives (orig/RFEE01/, private/, mods/, hd-textures, ...)
  3. type   it has a game/media/disc-image extension (.png, .tpl, .cmp, .brstm, .wbfs, ...)
  4. magic  its first bytes are a Nintendo/media container (Yaz0, U8, RARC, TPL, RSTM, THP,
            PNG, DDS, ...)
  5. binary it contains NUL bytes (the repo is source code; binaries need an allow.txt entry)
  6. marker it is generated game data that says so in its first line ("GENERATED by
            tools/port/gen_data.py", "Do not commit", the id/en/ja header of text_export.py)
  7. size   it is larger than --max-size (default 3 MiB)
  8. link   (pre-commit) it is a symlink into the disc, the mods folder or another absolute path

tools/guard/allow.txt lists path globs that may skip rules 3-7 (e.g. documentation
screenshots). Nothing skips rule 1 or 2.

Modes:
  pre-commit                  staged changes (git hook)
  pre-push                    reads the pre-push hook's stdin, checks every new commit
  --range A..B / REV...       every blob introduced by those commits (git rev-list --objects)
  --tree [REV]                every file of one tree (default HEAD)
  --history                   every blob ever committed on any ref
  --index                     only (re)build the local hash index and print its stats

Exit code 0 = clean, 1 = something was refused, 2 = usage/git error.
Bypassing with `git commit --no-verify` is possible, so the push hook and CI check again.
"""
