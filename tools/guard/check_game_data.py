# ---------------------------------------------------------------- git helpers

def git(*args, input=None, check=True):
    r = subprocess.run(("git",) + args, input=input, capture_output=True)
    if check and r.returncode != 0:
        sys.stderr.write(r.stderr.decode("utf-8", "replace"))
        raise SystemExit(2)
    return r.stdout


def git_text(*args):
    return git(*args).decode("utf-8", "surrogateescape").strip()


def common_dir():
    return os.path.abspath(git_text("rev-parse", "--git-common-dir"))


def guard_dir():
    d = os.path.join(common_dir(), "fe10-guard")
    os.makedirs(d, exist_ok=True)
    return d


class BlobReader:
    """Reads blobs through one `git cat-file --batch` process."""

    def __init__(self):
        self.p = subprocess.Popen(["git", "cat-file", "--batch"], stdin=subprocess.PIPE,
                                  stdout=subprocess.PIPE)

    def read(self, oid):
        self.p.stdin.write(oid.encode() + b"\n")
        self.p.stdin.flush()
        header = self.p.stdout.readline().split()
        if len(header) < 3 or header[1] == b"missing":
            return None, None
        kind, size = header[1].decode(), int(header[2])
        data = self.p.stdout.read(size)
        self.p.stdout.read(1)
        return kind, data

    def close(self):
        self.p.stdin.close()
        self.p.wait()


# ---------------------------------------------------------------- hash index

def git_blob_id(data):
    h = hashlib.sha1(b"blob %d\0" % len(data))
    h.update(data)
    return h.hexdigest()


SKIP_BUILD_EXT = {".o", ".obj", ".a", ".d", ".dep", ".elf", ".dol", ".rel", ".map", ".ninja",
                  ".log", ".pyc", ".dylib", ".so", ".dSYM", ".pch", ".gch", ".lock", ".json",
                  ".c", ".cpp", ".h", ".s", ".S", ".inc", ".txt"}


def index_roots():
    """(path, label, skip_ext) of every place that holds game data on this machine."""
    roots = []
    tops = []
    try:
        tops.append(git_text("rev-parse", "--show-toplevel"))
    except SystemExit:
        pass
    cd = common_dir()
    if os.path.basename(cd) == ".git":
        tops.append(os.path.dirname(cd))
    seen_tops = set()
    for top in tops:
        if not top or top in seen_tops:
            continue
        seen_tops.add(top)
        roots.append((os.path.join(top, "orig", "RFEE01"), "disc", None))
        parent = os.path.dirname(top)
        roots.append((os.path.join(parent, "private"), "private", None))
        roots.append((os.path.join(top, "private"), "private", None))
    home = os.path.expanduser("~")
    roots.append((os.path.join(home, "Library", "Application Support", "fe10_host"), "fe10_host", None))
    roots.append((os.path.join(home, ".local", "share", "fe10_host"), "fe10_host", None))
    for var in ("FE10_USER_DIR", "FE10_NAND_DIR", "FE10_SAVES", "FE10_PLAYTEST_REFS",
                "FE10_SHOT_DIR", "FE10_CLOUD_DIR", "FE10_GUARD_EXTRA"):
        for v in os.environ.get(var, "").split(os.pathsep):
            if v:
                roots.append((v, var, None))
    extra = os.path.join(guard_dir(), "roots.txt")
    if os.path.exists(extra):
        with open(extra, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith("#"):
                    roots.append((os.path.expanduser(line), "roots.txt", None))
    return roots


def walk_files(root, skip_ext):
    """Yields (shown path, real path) of every file under root, following symlinks once."""
    seen = set()
    stack = [root]
    while stack:
        d = stack.pop()
        try:
            real = os.path.realpath(d)
            if real in seen:
                continue
            seen.add(real)
            entries = list(os.scandir(d))
        except OSError:
            continue
        for e in entries:
            try:
                if e.is_dir(follow_symlinks=True):
                    if e.name in (".git", "obj", "__pycache__") and skip_ext is not None:
                        continue
                    stack.append(e.path)
                elif e.is_file(follow_symlinks=True):
                    if skip_ext is not None and os.path.splitext(e.name)[1] in skip_ext:
                        continue
                    yield e.path
            except OSError:
                continue


def load_index(path):
    entries = {}
    try:
        with open(path, encoding="utf-8", errors="surrogateescape") as f:
            if f.readline().rstrip("\n") != INDEX_VERSION:
                return entries
            for line in f:
                parts = line.rstrip("\n").split("\t")
                if len(parts) == 5:
                    p, size, mtime, oid, oid_lf = parts
                    entries[p] = (int(size), int(mtime), oid, oid_lf)
    except OSError:
        pass
    return entries


def build_index(verbose=False):
    """Refreshes the index (hashing only new/changed files). Returns {blob id: source path}."""
    gd = guard_dir()
    path = os.path.join(gd, "index.tsv")
    old = load_index(path)
    new = {}
    hashed = 0
    hashed_bytes = 0
    t0 = time.time()
    seen_paths = set()
    found_roots = []
    for root, label, skip_ext in index_roots():
        if not os.path.isdir(root):
            continue
        found_roots.append(root)
        for p in walk_files(root, skip_ext):
            if p in seen_paths:
                continue
            seen_paths.add(p)
            try:
                st = os.stat(p)
            except OSError:
                continue
            if st.st_size < MIN_HASH_SIZE or st.st_size > (4 << 30):
                continue
            prev = old.get(p)
            if prev and prev[0] == st.st_size and prev[1] == st.st_mtime_ns:
                new[p] = prev
                continue
            try:
                with open(p, "rb") as f:
                    data = f.read()
            except OSError:
                continue
            oid = git_blob_id(data)
            # `* text=auto` stores text with CRLF converted to LF: index that form too
            oid_lf = "-"
            if b"\r\n" in data and b"\0" not in data[:8000]:
                oid_lf = git_blob_id(data.replace(b"\r\n", b"\n"))
            new[p] = (st.st_size, st.st_mtime_ns, oid, oid_lf)
            hashed += 1
            hashed_bytes += len(data)
            if verbose and hashed % 2000 == 0:
                print("  hashed %d files (%.1f GB) ..." % (hashed, hashed_bytes / 1e9), file=sys.stderr)
    if new != old:
        tmp = path + ".tmp"
        with open(tmp, "w", encoding="utf-8", errors="surrogateescape") as f:
            f.write(INDEX_VERSION + "\n")
            for p, (size, mtime, oid, oid_lf) in sorted(new.items()):
                f.write("%s\t%d\t%d\t%s\t%s\n" % (p, size, mtime, oid, oid_lf))
        os.replace(tmp, path)
    lookup = {}
    for p, (_, _, oid, oid_lf) in new.items():
        lookup.setdefault(oid, p)
        if oid_lf != "-":
            lookup.setdefault(oid_lf, p)
    if verbose:
        print("fe10-guard index: %d files from %d folders (%d newly hashed, %.1f GB, %.1f s)"
              % (len(new), len(found_roots), hashed, hashed_bytes / 1e9, time.time() - t0),
              file=sys.stderr)
        for r in found_roots:
            print("  " + r, file=sys.stderr)
    return lookup, found_roots


# ---------------------------------------------------------------- allow list

def load_allow(source_text):
    pats = []
    for line in source_text.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            pats.append(line)
    return pats


def read_allow(mode):
    rel = "tools/guard/allow.txt"
    if mode == "pre-commit":
        r = subprocess.run(["git", "show", ":" + rel], capture_output=True)
        if r.returncode == 0:
            return load_allow(r.stdout.decode("utf-8", "replace"))
    try:
        top = git_text("rev-parse", "--show-toplevel")
        with open(os.path.join(top, rel), encoding="utf-8") as f:
            return load_allow(f.read())
    except (OSError, SystemExit):
        pass
    installed = os.path.join(common_dir(), "fe10-guard", "allow.txt")
    try:
        with open(installed, encoding="utf-8") as f:
            return load_allow(f.read())
    except OSError:
        return []


def matches(path, pats):
    return any(fnmatch.fnmatchcase(path, p) for p in pats)


# ---------------------------------------------------------------- checks

def check_blob(path, oid, data, allow, lookup, max_size, mode=None):
    """Returns a list of reasons why this blob must not be committed."""
    reasons = []
    lpath = path.lower()
    if lookup and oid in lookup:
        reasons.append("identical to game data file %s" % lookup[oid])
    for pat, why in PATH_RULES:
        if fnmatch.fnmatchcase(lpath, pat):
            reasons.append("path is " + why)
            break
    if mode == "120000":
        target = data.decode("utf-8", "replace")
        if target.startswith("/") or target.startswith("~") or "RFEE01" in target \
                or "Application Support" in target or "fe10_host" in target:
            reasons.append("symlink to %s (game data stays outside git)" % target)
        return reasons
    if matches(path, allow):
        return reasons
    base = os.path.basename(lpath)
    ext = os.path.splitext(base)[1]
    if ext in DENY_EXT or any(base.endswith(e) for e in (".tpl.cmp", ".m.cmp", ".bin.cmp")):
        reasons.append("file type %s is game/media data" % ext)
    for off, magic, name in MAGICS:
        if data[off:off + len(magic)] == magic:
            reasons.append("content is a %s" % name)
            break
    if b"\0" in data[:8000] and not any(r.startswith("content is") for r in reasons):
        reasons.append("binary content (the repo holds source code only)")
    first_line = data[:512].split(b"\n", 1)[0]
    for marker, why in MARKERS:
        if marker in first_line:
            reasons.append(why)
    if data.startswith(TEXT_EXPORT_HEADER) or data.startswith(b"source\tindex\tw\th\tfmt\tkey"):
        reasons.append("exported game table (tools/mods)")
    if len(data) > max_size:
        reasons.append("%.1f MiB is over the %.1f MiB limit" % (len(data) / 2**20, max_size / 2**20))
    return reasons


def staged_entries():
    out = git("diff", "--cached", "--raw", "-z", "--no-renames", "--diff-filter=ACMRT", "--no-abbrev")
    parts = out.split(b"\0")
    entries = []
    i = 0
    while i + 1 < len(parts):
        meta = parts[i].decode()
        path = parts[i + 1].decode("utf-8", "surrogateescape")
        i += 2
        if not meta.startswith(":"):
            continue
        fields = meta[1:].split()
        mode, oid = fields[1], fields[3]
        if mode == "160000":      # submodule
            continue
        entries.append((path, oid, mode))
    return entries


def rev_list_entries(revs):
    out = git("rev-list", "--objects", *revs)
    entries = []
    oids = []
    paths = []
    for line in out.decode("utf-8", "surrogateescape").splitlines():
        oid, _, path = line.partition(" ")
        if path:
            oids.append(oid)
            paths.append(path)
    if not oids:
        return entries
    kinds = git("cat-file", "--batch-check=%(objecttype)", input=("\n".join(oids) + "\n").encode())
    for oid, path, kind in zip(oids, paths, kinds.decode().split("\n")):
        if kind == "blob":
            entries.append((path, oid, None))
    return entries


def tree_entries(rev):
    out = git("ls-tree", "-r", "-z", "--full-tree", rev)
    entries = []
    for rec in out.split(b"\0"):
        if not rec:
            continue
        meta, _, path = rec.partition(b"\t")
        mode, kind, oid = meta.decode().split()
        if kind == "blob":
            entries.append((path.decode("utf-8", "surrogateescape"), oid, mode))
    return entries


def pre_push_revs(stdin_text):
    zero = "0" * 40
    revs = []
    for line in stdin_text.splitlines():
        parts = line.split()
        if len(parts) != 4:
            continue
        _, local_sha, _, remote_sha = parts
        if local_sha == zero:
            continue          # deleting a branch
        if remote_sha != zero and subprocess.run(["git", "cat-file", "-e", remote_sha + "^{commit}"],
                                                 capture_output=True).returncode == 0:
            revs.append((local_sha, ["^" + remote_sha]))
        else:
            revs.append((local_sha, ["--not", "--remotes"]))
    return revs


def run_checks(entries, allow, lookup, max_size):
    problems = []
    seen = set()
    reader = BlobReader()
    try:
        for path, oid, mode in entries:
            key = (path, oid)
            if key in seen:
                continue
            seen.add(key)
            kind, data = reader.read(oid)
            if kind != "blob":
                continue
            reasons = check_blob(path, oid, data, allow, lookup, max_size, mode)
            if reasons:
                problems.append((path, oid, reasons))
    finally:
        reader.close()
    return problems


def report(problems, mode):
    if not problems:
        return 0
    w = sys.stderr.write
    w("\n*** fe10 game-data guard: %d file(s) refused (%s) ***\n\n" % (len(problems), mode))
    for path, oid, reasons in problems[:200]:
        w("  %s\n" % path)
        for r in reasons:
            w("      - %s\n" % r)
    if len(problems) > 200:
        w("  ... and %d more\n" % (len(problems) - 200))
    w("\nThis repository must never contain game data (disc files, extracted or generated\n"
      "assets, game text, saves, screenshots, HD textures).\n")
    if mode == "pre-commit":
        w("Unstage these files:  git restore --staged <file>   (and add them to .gitignore)\n")
    elif mode == "pre-push":
        w("Remove the files from the commits that are not pushed yet (git rebase -i / --amend)\n"
          "before pushing. Do not push them 'just once': git history keeps them forever.\n")
    w("A harmless source/doc file that trips rules 3-7 can be listed in tools/guard/allow.txt.\n\n")
    return 1


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("mode", nargs="?", choices=["pre-commit", "pre-push"])
    ap.add_argument("remote", nargs="*", help=argparse.SUPPRESS)
    ap.add_argument("--range", nargs="+", metavar="REV", help="check blobs introduced by these revs")
    ap.add_argument("--tree", nargs="?", const="HEAD", metavar="REV", help="check one whole tree")
    ap.add_argument("--history", action="store_true", help="check every blob on every ref")
    ap.add_argument("--index", action="store_true", help="rebuild the hash index and show stats")
    ap.add_argument("--no-hash", action="store_true", help="skip the hash index (rules 2-8 only)")
    ap.add_argument("--max-size", type=int, default=int(os.environ.get("FE10_GUARD_MAX_SIZE", MAX_SIZE_DEFAULT)))
    a = ap.parse_args()

    if a.index:
        lookup, roots = build_index(verbose=True)
        if not roots:
            print("no game-data folders found on this machine (hash rule inactive)", file=sys.stderr)
        return 0

    lookup = {}
    if not a.no_hash and not os.environ.get("CI"):
        lookup, _ = build_index(verbose=False)

    if a.mode == "pre-commit":
        entries = staged_entries()
    elif a.mode == "pre-push":
        entries = []
        for local_sha, exclude in pre_push_revs(sys.stdin.read()):
            entries += rev_list_entries([local_sha] + exclude)
    elif a.range:
        entries = rev_list_entries(a.range)
    elif a.tree:
        entries = tree_entries(a.tree)
    elif a.history:
        entries = rev_list_entries(["--all"])
    else:
        ap.print_help()
        return 2
    mode = a.mode or ("history" if a.history else "tree " + a.tree if a.tree else "range")
    problems = run_checks(entries, read_allow(a.mode), lookup, a.max_size)
    rc = report(problems, mode)
    if rc == 0 and not a.mode:
        print("fe10 game-data guard: %d blob(s) checked, nothing refused%s"
              % (len(entries), "" if lookup else " (no hash index on this machine)"))
    return rc


if __name__ == "__main__":
    sys.exit(main())
